# -*- coding: utf-8 -*-
"""Имена выходных файлов: участок и вид работ прямо в названии.

Файлы уходят заказчику и специалисту по одному, вне своей папки, и
«Пояснительная_записка.pdf» из трёх разных комплектов — это три файла
с одним именем. Поэтому каждое имя начинается с кадастрового номера и
вида работ.
"""
import re

WORK_DEFAULT = 'анализ зарастания'

def tag(kn):
    """Кадастровый номер в виде, пригодном для имени файла."""
    return (kn or '').replace(':', '-').strip()

def slug(text):
    """Текст → часть имени файла: без пробелов и служебных символов."""
    t = re.sub(r'[\\/:*?"<>|]+', '', (text or '').strip())
    return re.sub(r'\s+', '_', t)

def work_of(cfg):
    return (cfg.get('вид_работ') or cfg.get('work') or WORK_DEFAULT).strip()

def prefix(cfg):
    """«58-24-0341802-1173_анализ_зарастания»."""
    return '%s_%s' % (tag(cfg.get('kn', '')), slug(work_of(cfg)))

def fname(cfg, base):
    """Полное имя файла комплекта: участок, вид работ, название документа."""
    return '%s_%s' % (prefix(cfg), base)

def doc_kind(filename):
    """Название документа из имени файла — префикс участка отбрасывается."""
    name = filename.rsplit('/', 1)[-1]
    for known in KNOWN:
        if name.endswith(known):
            return known
    return name

KNOWN = ('Схема_ЧЗУ.pdf', 'Проверочная_карта.pdf', 'Пояснительная_записка.pdf',
         'Приложение_ИК.pdf', 'Приложение_динамика.pdf', 'Приложение_рельеф.pdf',
         'Приложение_почвы.pdf', 'Приложение_архив.pdf')
