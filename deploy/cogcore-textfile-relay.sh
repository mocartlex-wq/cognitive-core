#!/bin/bash
# Переносит метрики соседнего контура в каталог textfile-сборщика node_exporter.
#
# Почему копирует ПОТРЕБИТЕЛЬ, а не производитель. Изначально файл должен был
# уносить cron соседнего контура. Он туда не доехал и не доехал бы никогда:
# /etc/cron.d ставился отдельным скриптом с рабочей машины и выкатом не
# обновлялся — то есть часть механизма жила вне конвейера, который её должен
# доставлять, и при этом выглядела доставленной.
#
# Правка симптома (положить строку в /etc/cron.d руками) воспроизвела бы ровно
# эту причину. Поэтому копирование переехало на сторону того, кто метрикой
# пользуется: сосед пишет только к себе, мы читаем у него и пишем только к
# себе. Никто не пишет в чужой каталог, и чинит копирование тот, кому оно
# нужно.
#
# За смертью самого этого копира следить отдельно не нужно: он переносит
# ЧУЖУЮ отметку времени, и если он встанет, отметка в приёмнике замрёт.
# Правило CRMMonitorSilent смотрит на возраст отметки, а не на наличие файла,
# поэтому ловит и замолчавший монитор, и замолчавший копир — одинаково.
set -uo pipefail

SRC="${RELAY_SRC:-/opt/ai-crm/audit/crm_monitor.prom}"
DST_DIR="${RELAY_DST_DIR:-/var/lib/node_exporter/textfile}"
DST="$DST_DIR/crm_monitor.prom"
REQUIRED_METRIC="crm_monitor_heartbeat_seconds"

# Источника нет — НИЧЕГО не делаем и старый файл не трогаем. Удалить его
# значило бы заменить сигнал «отметка устарела» на «метрики нет вовсе»:
# первое видно правилом по возрасту, второе выглядит как «ещё не настроили».
[ -r "$SRC" ] || exit 0

# Пустой или обрезанный файл не переносим: лучше старая отметка, которая
# состарится и поднимет тревогу, чем свежий мусор, который её снимет.
[ -s "$SRC" ] || exit 0
grep -q "$REQUIRED_METRIC" "$SRC" || exit 0

mkdir -p "$DST_DIR" 2>/dev/null || true

# Временный файл — В ТОМ ЖЕ каталоге, иначе mv между файловыми системами
# перестаёт быть атомарным и сборщик может прочитать половину.
TMP="$DST.tmp.$$"
cp -- "$SRC" "$TMP" 2>/dev/null || { rm -f -- "$TMP"; exit 0; }
mv -f -- "$TMP" "$DST" 2>/dev/null || rm -f -- "$TMP"
exit 0
