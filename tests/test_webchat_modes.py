"""Три режима витрины чата: телефон, светлая тема, рамка витрины.

Проверка после десктоп-пасса №2 нашла в них две вещи (обе — про то, что
десктопный проход их не касался, а раньше никто не смотрел):

1. чипы «Кому» в светлой теме оставались с тёмной подложкой — белое на
   белом, от чипа виднелась только волосяная рамка;
2. телефон в альбомной ориентации: шапка, чипы, композер и таб-бар
   занимали 210 точек из 389, на переписку оставалось 179 — одно
   сообщение на экране.

Проверяем по исходнику, как в соседних тестах.
"""
from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
WEBCHAT = (ROOT / "sandbox" / "webchat.html").read_text(encoding="utf-8")


def _медиа(условие: str) -> str:
    """Тело медиа-запроса целиком — со вложенными правилами."""
    i = WEBCHAT.index(f"@media ({условие})")
    начало = WEBCHAT.index("{", i)
    глубина, к = 0, начало
    for к in range(начало, len(WEBCHAT)):
        if WEBCHAT[к] == "{":
            глубина += 1
        elif WEBCHAT[к] == "}":
            глубина -= 1
            if глубина == 0:
                break
    return WEBCHAT[начало: к + 1]


def test_чипы_кому_видны_в_светлой_теме():
    assert ".app.light .rcp-chip{background:rgba(0,0,0,.05)}" in WEBCHAT


def test_светлой_теме_подложки_заданы_всем_полям_композера():
    """#box, чипы вложений и чипы «Кому» — один и тот же приём."""
    for правило in (".app.light #box{", ".app.light .att-chip{", ".app.light .rcp-chip{"):
        assert правило in WEBCHAT, правило


def test_телефон_в_альбоме_ужимает_полосы():
    тело = _медиа("max-height: 460px")
    for селектор in (".vhead{", ".tab{", ".rcp-bar{", ".composer{", "#box{"):
        assert селектор in тело, селектор
    # безопасная зона айфона остаётся в расчёте отступа шапки
    assert "env(safe-area-inset-top,0px)" in тело


def test_ужатие_только_по_высоте_а_не_по_ширине():
    """Правило не должно задевать обычный телефон в портрете (852 точки)."""
    m = re.search(r"@media \(max-height: 460px\)", WEBCHAT)
    assert m, "нет правила для низкого экрана"
    хвост = WEBCHAT[m.start(): m.start() + 60]
    assert "width" not in хвост, "условие должно быть только по высоте"


def test_подписи_вкладок_остаются():
    """Иконки без подписей экономят 6 точек и стоят понятности — не берём."""
    тело = _медиа("max-height: 460px")
    assert ".tab span{display:none}" not in тело
